create table if not exists public.advanced_preliminary_analysis_runs (
    id uuid primary key default gen_random_uuid(),
    run_number bigint generated by default as identity unique not null,
    status text not null default 'queued'
        check (status in (
            'queued', 'processing', 'completed',
            'completed_with_failures', 'cancelled', 'failed'
        )),
    source_scope text not null default 'all_formally_completed_transcripts'
        check (source_scope = 'all_formally_completed_transcripts'),
    provider text not null,
    model text not null,
    resolved_model text,
    reasoning_effort text not null
        check (reasoning_effort in ('low', 'medium', 'high', 'xhigh', 'max')),
    analysis_version text not null,
    prompt_version text not null,
    prior_analysis_role text not null default 'preserved_preliminary_comparison',
    stop_layer text not null default 'preliminary_categories'
        check (stop_layer = 'preliminary_categories'),
    project_snapshot jsonb not null default '[]'::jsonb,
    source_case_count integer not null default 0 check (source_case_count >= 0),
    pending_count integer not null default 0 check (pending_count >= 0),
    processing_count integer not null default 0 check (processing_count >= 0),
    completed_count integer not null default 0 check (completed_count >= 0),
    failed_count integer not null default 0 check (failed_count >= 0),
    requested_by text not null default 'researcher',
    requested_at timestamptz not null default now(),
    model_verified_at timestamptz,
    started_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    cancellation_reason text,
    updated_at timestamptz not null default now(),
    last_error text,
    constraint advanced_preliminary_run_identity_nonempty check (
        btrim(provider) <> ''
        and btrim(model) <> ''
        and btrim(analysis_version) <> ''
        and btrim(prompt_version) <> ''
    )
);

